import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { extname, join, relative, sep } from "node:path";

const ROOT = join(import.meta.dirname, "..", "..");
const DIST = join(ROOT, "ui", "dist");
const OUT = join(ROOT, "src", "cli", "ui", "assets.ts");

const TYPES: Readonly<Record<string, string>> = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".mjs": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".map": "application/json; charset=utf-8",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".gif": "image/gif",
  ".webp": "image/webp",
  ".ico": "image/x-icon",
  ".woff": "font/woff",
  ".woff2": "font/woff2",
  ".ttf": "font/ttf",
  ".txt": "text/plain; charset=utf-8",
};

export interface PageFile {
  /** Under the build folder, with `/` between parts. */
  path: string;
  bytes: Buffer;
}

/** Every file of the page's build, in a stable order. */
export function pageFiles(dist: string): PageFile[] {
  const found: PageFile[] = [];
  const walk = (folder: string) => {
    for (const entry of readdirSync(folder, { withFileTypes: true })) {
      const full = join(folder, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (entry.isFile()) {
        found.push({ path: relative(dist, full).split(sep).join("/"), bytes: readFileSync(full) });
      }
    }
  };
  walk(dist);
  // Paths are unique, so two never compare equal.
  return found.sort((a, b) => (a.path < b.path ? -1 : 1));
}

/**
 * A module, so the npm build, the standalone binary and `pnpm dev` all carry the page.
 * Bodies are base64, so no linter reads the page as TypeScript, and the layout is the
 * formatter's own, so formatting the tree never makes it stale.
 */
export function render(files: readonly PageFile[]): string {
  const assets = files.map(({ path, bytes }) => {
    const type = TYPES[extname(path).toLowerCase()];
    if (type === undefined) throw new Error(`ui/dist/${path}: no content type for its extension`);
    // Vite names everything under assets/ by its content hash.
    const immutable = path.startsWith("assets/");
    return [
      `  ${JSON.stringify(path === "index.html" ? "/" : `/${path}`)}: {`,
      `    type: ${JSON.stringify(type)},`,
      `    immutable: ${immutable},`,
      "    body: bytes(",
      `      "${bytes.toString("base64")}",`,
      "    ),",
      "  },",
    ].join("\n");
  });
  return [
    "// Generated by `pnpm run ui` from ui/dist, and not committed.",
    'import type { ServeOptions } from "./server.ts";',
    "",
    'const bytes = (base64: string) => Buffer.from(base64, "base64");',
    "",
    'export const ASSETS: ServeOptions["assets"] = {',
    ...assets,
    "};",
    "",
  ].join("\n");
}

if (process.argv[1]?.endsWith("build.ts") === true) {
  if (!existsSync(join(DIST, "index.html"))) {
    process.stderr.write("ui/dist/index.html is missing; build the page first\n");
    process.exit(1);
  }
  const text = render(pageFiles(DIST));
  // An unchanged module keeps its time, so a build made from it still reads as current.
  if (current(OUT) === text) {
    process.stdout.write("src/cli/ui/assets.ts is current\n");
  } else {
    writeFileSync(OUT, text);
    process.stdout.write(`wrote src/cli/ui/assets.ts (${Math.round(text.length / 1024)} KiB)\n`);
  }
}

/** Read in one step, so no check can go stale before the read. */
function current(path: string): string | undefined {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return undefined;
  }
}
