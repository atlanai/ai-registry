import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..", "..");
const PAGE = join(ROOT, "ui", "public");
const OUT = join(ROOT, "src", "cli", "ui", "assets.ts");

/** The page's own files, by the path the server serves each at. */
const MODULES = ["core", "markdown", "catalog", "machine", "dialogs", "main"];

const FILES: readonly [path: string, file: string, type: string][] = [
  ["/", "index.html", "text/html; charset=utf-8"],
  ["/style.css", "style.css", "text/css; charset=utf-8"],
  ...MODULES.map((name): [string, string, string] => [
    `/js/${name}.js`,
    `js/${name}.js`,
    "text/javascript; charset=utf-8",
  ]),
];

/**
 * A module, so the npm build, the standalone binary and `pnpm dev` all carry the page.
 * Bodies are base64, so no linter reads the page as TypeScript, and the layout is the
 * formatter's own, so formatting the tree never makes it stale.
 */
export function render(bodies: readonly string[]): string {
  const assets = FILES.map(([path, , type], at) =>
    [
      `  ${JSON.stringify(path)}: {`,
      `    type: ${JSON.stringify(type)},`,
      "    body: text(",
      `      "${Buffer.from(bodies[at] ?? "", "utf8").toString("base64")}",`,
      "    ),",
      "  },",
    ].join("\n"),
  );
  return [
    "// Generated by scripts/ui/build.ts from ui/public. Run `pnpm run ui` after changing the page.",
    'import type { Asset } from "./server.ts";',
    "",
    'const text = (base64: string) => Buffer.from(base64, "base64").toString("utf8");',
    "",
    "export const ASSETS: Readonly<Record<string, Asset>> = {",
    ...assets,
    "};",
    "",
  ].join("\n");
}

if (process.argv[1]?.endsWith("build.ts") === true) {
  const text = render(FILES.map(([, file]) => readFileSync(join(PAGE, file), "utf8")));
  if (process.argv.includes("--check")) {
    const stale = readFileSync(OUT, "utf8") !== text;
    if (stale) process.stderr.write("src/cli/ui/assets.ts is stale; run `pnpm run ui`\n");
    if (stale) process.exit(1);
    process.stdout.write("src/cli/ui/assets.ts is current\n");
  } else {
    writeFileSync(OUT, text);
    process.stdout.write(`wrote src/cli/ui/assets.ts (${Math.round(text.length / 1024)} KiB)\n`);
  }
}
